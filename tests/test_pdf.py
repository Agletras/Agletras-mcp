"""Tests for PDF text extraction."""

from __future__ import annotations

from agletras_mcp import pdf
from agletras_mcp.config import load_settings
from agletras_mcp.errors import ToolError

from tests.support import SAMPLE_PAGES, TempHomeCase, serve_http


class PdfExtractionTests(TempHomeCase):
    def setUp(self) -> None:
        super().setUp()
        self.settings = load_settings()

    def extract(self, source: str, **kwargs):
        return pdf.extract_text(source, settings=self.settings, **kwargs)

    def test_extracts_text_and_metadata_from_sample(self) -> None:
        sample = self.write_sample_pdf()
        result = self.extract(str(sample))
        self.assertEqual(result["page_count"], 2)
        self.assertEqual(result["pages_extracted"], 2)
        self.assertTrue(result["has_text"])
        self.assertIn("AGLETRAS_SAMPLE_2026", result["text"])
        self.assertIn("PDF_OK_TOKEN", result["text"])
        self.assertIn("--- page 1/2 ---", result["text"])
        self.assertIn("--- page 2/2 ---", result["text"])
        self.assertEqual(result["metadata"].get("title"), "Agentic Research Pipelines: A Sample Paper")
        self.assertIn("Agletras Research", result["metadata"].get("author", ""))
        self.assertFalse(result["truncated"])
        self.assertEqual(result["warnings"], [])

    def test_relative_path_resolves_against_project_root(self) -> None:
        # The project ships samples/sample-research-paper.pdf (generated by
        # scripts/make_sample_pdf.py); skip gracefully if it was not generated.
        sample = self.settings.project_root / "samples" / "sample-research-paper.pdf"
        if not sample.exists():
            self.skipTest("sample PDF not generated yet; run scripts/make_sample_pdf.py")
        result = self.extract("samples/sample-research-paper.pdf")
        self.assertIn("AGLETRAS_SAMPLE_2026", result["text"])

    def test_max_pages_and_max_chars_limits(self) -> None:
        sample = self.write_sample_pdf()
        limited_pages = self.extract(str(sample), max_pages=1)
        self.assertEqual(limited_pages["pages_extracted"], 1)
        self.assertNotIn("AGLETRAS_SAMPLE_2026 appears on this page", limited_pages["text"])
        self.assertTrue(any("first 1 of 2 pages" in warning for warning in limited_pages["warnings"]))

        limited_chars = self.extract(str(sample), max_chars=30)
        self.assertTrue(limited_chars["truncated"])
        self.assertEqual(len(limited_chars["text"]), 30)

    def test_blank_pdf_reports_no_text_warning(self) -> None:
        blank = self.write_sample_pdf(name="blank.pdf", pages=[[]])
        result = self.extract(str(blank))
        self.assertFalse(result["has_text"])
        self.assertTrue(any("scanned" in warning for warning in result["warnings"]))

    def test_missing_file(self) -> None:
        with self.assertRaises(ToolError) as ctx:
            self.extract(str(self.home / "nope.pdf"))
        self.assertEqual(ctx.exception.code, "not_found")

    def test_non_pdf_file_rejected(self) -> None:
        fake = self.home / "notes.pdf"
        fake.write_text("this is plain text, not a pdf", encoding="utf-8")
        with self.assertRaises(ToolError) as ctx:
            self.extract(str(fake))
        self.assertEqual(ctx.exception.code, "unsupported_content")

    def test_corrupt_pdf_raises_pdf_error(self) -> None:
        broken = self.home / "broken.pdf"
        broken.write_bytes(b"%PDF-1.4\nthis is not a real pdf body")
        with self.assertRaises(ToolError) as ctx:
            self.extract(str(broken))
        self.assertEqual(ctx.exception.code, "pdf_error")

    def test_extraction_from_url_uses_cache(self) -> None:
        sample_bytes = (self.write_sample_pdf()).read_bytes()
        with serve_http({"/paper.pdf": (200, "application/pdf", sample_bytes)}) as base:
            result = self.extract(f"{base}/paper.pdf")
            self.assertEqual(result["page_count"], 2)
            self.assertIn("AGLETRAS_SAMPLE_2026", result["text"])
            self.assertTrue(result["url"].endswith("/paper.pdf"))
            self.assertTrue(result["path"].startswith(str(self.home / "cache")))

    def test_empty_source_argument(self) -> None:
        with self.assertRaises(ToolError) as ctx:
            self.extract("   ")
        self.assertEqual(ctx.exception.code, "invalid_argument")

    def test_sample_pages_constant_has_two_pages(self) -> None:
        self.assertEqual(len(SAMPLE_PAGES), 2)
